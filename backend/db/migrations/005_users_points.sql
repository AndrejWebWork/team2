-- ==========================================================================
-- Миграција 005 — колона `points` кај корисниците (гамификација)
-- --------------------------------------------------------------------------
-- Тековен збир на поени по корисник. Правила:
--   * 1 поен за поднесена пријава (само контејнер/дива депонија),
--   * +2 поени кога пријавата е решена (вкупно 3),
--   * анонимните корисници немаат поени.
-- Изврши еднаш врз постоечка база:
--   psql "$DATABASE_URL" -f backend/db/migrations/005_users_points.sql
-- ==========================================================================

ALTER TABLE users
  ADD COLUMN IF NOT EXISTS points INTEGER NOT NULL DEFAULT 0;

-- Пополни го агрегатот од историјата на поени (points_events).
UPDATE users u
   SET points = COALESCE((
     SELECT SUM(pe.points) FROM points_events pe WHERE pe.user_id = u.id
   ), 0);
